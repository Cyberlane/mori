	bash := filepath.Join(root, "build")
	unsupported := filepath.Join(root, "fish-tool")
	writeFixture(t, zsh, "#!/bin/zsh\nrun() { print ok; }\n")
	writeFixture(t, bash, "#!/usr/bin/env -S bash -eu\nrun() { printf '%s\\n' ok; }\n")
