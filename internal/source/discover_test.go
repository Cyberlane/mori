func TestDiscoverClassifiesAndOptionallyExcludesGeneratedFiles(t *testing.T) {
	t.Parallel()

	root := t.TempDir()
	generatedGo := filepath.Join(root, "generated.go")
	generatedTS := filepath.Join(root, "routeTree.gen.ts")
	generatedSwift := filepath.Join(root, "APITypes.swift")
	generatedSwiftProtobuf := filepath.Join(root, "model.pb.swift")
	handwritten := filepath.Join(root, "main.go")
	stringLiteral := filepath.Join(root, "literal.go")
	nonTypeshare := filepath.Join(root, "generator.swift")
	nonSwiftProtobuf := filepath.Join(root, "protobuf-helper.swift")
	writeFixture(t, generatedGo, "// Code generated by sqlc. DO NOT EDIT.\npackage fixture\n")
	writeFixture(t, generatedTS, "// This file was automatically generated by TanStack Router.\nexport function route() {}\n")
	writeFixture(t, generatedSwift, "/*\n Generated by typeshare 1.13.4\n */\nfunc decode() {}\n")
	writeFixture(t, generatedSwiftProtobuf, "// DO NOT EDIT.\n// swift-format-ignore-file\n// swiftlint:disable all\n//\n// Generated by the Swift generator plugin for the protocol buffer compiler.\n// Source: model.proto\nfunc decode() {}\n")
	writeFixture(t, handwritten, "package fixture\n")
	writeFixture(t, stringLiteral, "package fixture\nconst warning = \"Code generated; DO NOT EDIT\"\n")
	writeFixture(t, nonTypeshare, "// Generated by a project helper\nfunc build() {}\n")
	writeFixture(t, nonSwiftProtobuf, "// DO NOT EDIT.\n// Generated by the Swift build helper.\nfunc build() {}\n")

	included := Discover([]string{root}, Options{})
	if len(included.Files) != 8 || len(included.Excluded) != 0 {
		t.Fatalf("included result = %#v, want eight files", included)
	}
	generated := 0
	for _, file := range included.Files {
		if file.Generated {
			generated++
		}
	}
	if generated != 4 {
		t.Fatalf("generated files = %d, want 4: %#v", generated, included.Files)
	}

	excluded := Discover([]string{root}, Options{ExcludeGenerated: true})
	if len(excluded.Files) != 4 || len(excluded.Excluded) != 4 {
		t.Fatalf("excluded result = %#v, want four analyzed and four excluded", excluded)
	}
	markers := make(map[string]bool)
	for _, coverage := range excluded.Excluded {
		if coverage.Status != "excluded_generated" || !coverage.Generated || coverage.GeneratedMarker == "" ||
			coverage.ZeroReason != "generated_excluded" {
			t.Fatalf("excluded coverage = %#v", coverage)
		}
		markers[coverage.GeneratedMarker] = true
	}
	if !markers["typeshare-generated"] {
		t.Fatalf("generated markers = %#v, want Typeshare", markers)
	}
	if !markers["swift-protobuf-generated"] {
		t.Fatalf("generated markers = %#v, want SwiftProtobuf", markers)
	}
}

